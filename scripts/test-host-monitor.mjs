import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const code=readFileSync(new URL('../assets/monitor.js',import.meta.url),'utf8');
const context=vm.createContext({numeric:value=>typeof value==='number'&&Number.isFinite(value)});
vm.runInContext(code,context);
for(const [value,expected] of [[null,'—'],[0,'0 B'],[1024,'1 KiB'],[1073741824,'1 GiB']])assert.equal(vm.runInContext(`hostBytes(${JSON.stringify(value)})`,context),expected);
assert.equal(vm.runInContext('hostPercent(null)',context),'Collecting…');
vm.runInContext('rememberHost("cpu", 10, 20); rememberHost("cpu", 15, null); rememberHost("cpu", 15, 30); rememberHost("cpu", 11, 90)',context);
assert.equal(vm.runInContext('hostHistory.get("cpu").length',context),2);
assert.equal(vm.runInContext('hostHistory.get("cpu")[1].value',context),30);
vm.runInContext('rememberHost("cpu",20,NaN)',context);
assert.equal(vm.runInContext('hostHistory.get("cpu")[2].value',context),null,'Missing samples stay gaps, not zero');
vm.runInContext('for(let at=30;at<4000;at+=5)rememberHost("cpu",at,1)',context);
assert.ok(vm.runInContext('hostHistory.get("cpu").length <= 720',context));
assert.ok(vm.runInContext('hostHistory.get("cpu")[0].at >= 3995 - 3600',context));
const html=readFileSync(new URL('../assets/index.html',import.meta.url),'utf8');
for(const [,id] of code.matchAll(/\$\("([^"]+)"\)/g))assert.ok(html.includes(`id="${id}"`),`Missing host DOM target ${id}`);
console.log('Host monitor checks passed: units, unknown readings, ordered bounded history and DOM targets.');
